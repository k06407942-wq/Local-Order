function translateValue(value, language) {
    const dictionary = language === 'en' ? LANGUAGE_TEXT : ENGLISH_TEXT;
    const keys = language === 'en' ? LANGUAGE_KEYS : ENGLISH_KEYS;
    let translated = value;

    for (const key of keys) {
        if (translated === key) return dictionary[key];
        const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        translated = translated.replace(
            new RegExp(`(^|[^\\p{L}\\p{N}])(${escapedKey})(?=$|[^\\p{L}\\p{N}])`, 'gu'),
            (_, prefix) => prefix + dictionary[key]
        );
    }

    return translated;
}

function translateElement(element, language) {
    if (element.nodeType === Node.TEXT_NODE) {
        const translated = translateValue(element.nodeValue, language);
        if (translated !== element.nodeValue) element.nodeValue = translated;
        return;
    }

    if (element.nodeType !== Node.ELEMENT_NODE && element.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
    if (element.nodeType === Node.ELEMENT_NODE && /^(SCRIPT|STYLE)$/.test(element.tagName)) return;

    const translateAttributes = target => {
        for (const attribute of TRANSLATABLE_ATTRIBUTES) {
            if (!target.hasAttribute(attribute)) continue;
            const value = target.getAttribute(attribute);
            const translated = translateValue(value, language);
            if (translated !== value) target.setAttribute(attribute, translated);
        }
    };

    if (element.nodeType === Node.ELEMENT_NODE) translateAttributes(element);
    const walker = document.createTreeWalker(
        element,
        NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
        {
            acceptNode(node) {
                return node.nodeType === Node.ELEMENT_NODE && /^(SCRIPT|STYLE)$/.test(node.tagName)
                    ? NodeFilter.FILTER_REJECT
                    : NodeFilter.FILTER_ACCEPT;
            }
        }
    );
    let node;
    while ((node = walker.nextNode())) {
        if (node.nodeType === Node.ELEMENT_NODE) {
            translateAttributes(node);
        } else {
            const translated = translateValue(node.nodeValue, language);
            if (translated !== node.nodeValue) node.nodeValue = translated;
        }
    }
}

function updateLanguageButton(button, language) {
    const isRussian = language === 'ru';
    button.textContent = isRussian ? 'EN' : 'РУ';
    button.setAttribute('aria-label', isRussian ? 'Switch to English' : 'Переключить на русский');
    button.title = isRussian ? 'Switch to English' : 'Переключить на русский';
}

function setLanguage(language) {
    currentLanguage = language === 'en' ? 'en' : 'ru';
    document.documentElement.lang = currentLanguage;
    localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
    translateElement(document.body, currentLanguage);

    const button = document.getElementById('language-toggle');
    if (button) updateLanguageButton(button, currentLanguage);
}

